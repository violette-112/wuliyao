/**
 * 构建完整的96色调色板数组
 */
function buildPalette() {
  const palette = [];

  for (let r = 0; r < PALETTE_ROWS; r++) {
    for (let c = 0; c < PALETTE_COLS; c++) {
      const rgb = baseColors[r][c][0];
      palette.push({
        rgb,
        hex: rgbToHex(rgb),
        coord: `R${r + 1}·C${c + 1}`,
        row: r + 1,
        col: c + 1,
        isAccent: false,
      });
    }
  }

  for (let i = 0; i < accentColors.length; i++) {
    const rgb = accentColors[i];
    palette.push({
      rgb,
      hex: rgbToHex(rgb),
      coord: `A${i + 1}`,
      row: null,
      col: null,
      isAccent: true,
    });
  }

  return palette;
}

function rgbToHex([r, g, b]) {
  return (
    "#" +
    [r, g, b]
      .map((x) => {
        const hex = x.toString(16);
        return hex.length === 1 ? "0" + hex : hex;
      })
      .join("")
  ).toUpperCase();
}

export const TOMODACHI_PALETTE = buildPalette();
